
import pandas as pd

# Path to prediction CSV
path = "results/metrics/adl-01-cam0_predictions.csv"

# Load CSV
df = pd.read_csv(path)

# Convert numeric columns
numeric_columns = [
    "frame",
    "timestamp",
    "torso_angle",
    "hip_speed"
]

for column in numeric_columns:
    df[column] = pd.to_numeric(
        df[column],
        errors="coerce"
    )

print("\n========== VIDEO SUMMARY ==========")

print("Total frames:", len(df))

print(
    "Video duration:",
    round(df["timestamp"].max(), 3),
    "seconds"
)

print("\n========== VISIBLE STATE COUNTS ==========")

print(df["state"].value_counts(dropna=False))

# Check whether the new detector_state column exists
if "detector_state" in df.columns:

    print("\n========== INTERNAL DETECTOR STATE COUNTS ==========")

    print(
        df["detector_state"].value_counts(dropna=False)
    )

else:

    print("\nWARNING: detector_state column not found.")
    print("This may be an older CSV generated by the previous code.")

print("\n========== TORSO ANGLE STATISTICS ==========")

print(df["torso_angle"].describe())

print("\n========== HIP SPEED STATISTICS ==========")

print(df["hip_speed"].describe())

# Possible fall frames
print("\n========== POSSIBLE FALL FRAMES ==========")

possible_fall = df[
    (df["state"] == "POSSIBLE_FALL")
]

if not possible_fall.empty:
    print(possible_fall.to_string(index=False))
else:
    print("No POSSIBLE_FALL frames found.")

# Confirmed fall frames
print("\n========== FALL DETECTED FRAMES ==========")

if "detector_state" in df.columns:

    fall_frames = df[
        df["detector_state"] == "FALL_DETECTED"
    ]

else:

    fall_frames = df[
        df["state"] == "FALL_DETECTED"
    ]

if not fall_frames.empty:
    print(fall_frames.to_string(index=False))
else:
    print("No FALL_DETECTED frames found.")

# Missing person frames
print("\n========== NO PERSON FRAMES ==========")

no_person = df[
    df["state"] == "NO_PERSON"
]

print("Total NO_PERSON frames:", len(no_person))

if not no_person.empty:

    print(
        no_person[
            ["frame", "timestamp", "state"]
        ].to_string(index=False)
    )

# Detailed fall region
print("\n========== DETAILED FALL REGION (95-130) ==========")

region = df[
    (df["frame"] >= 95)
    & (df["frame"] <= 130)
]

columns = [
    "frame",
    "timestamp",
    "torso_angle",
    "hip_speed",
    "state"
]

if "detector_state" in df.columns:
    columns.append("detector_state")

if not region.empty:
    print(region[columns].to_string(index=False))
else:
    print("No frames found in this range.")

# Show detector state transitions
if "detector_state" in df.columns:

    print("\n========== DETECTOR STATE TRANSITIONS ==========")

    changed = (
        df["detector_state"]
        != df["detector_state"].shift()
    )

    transitions = df.loc[
        changed,
        ["frame", "timestamp", "detector_state"]
    ]

    print(transitions.to_string(index=False))

print("\n========== ANALYSIS COMPLETED ==========")
